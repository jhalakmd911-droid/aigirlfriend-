// API বন্ধ হলে এই ফাংশনটি উত্তর তৈরি করবে
export function getOfflineResponse(
  characterId: string,
  userMessage: string
): string {
  const kb = characterKnowledge[characterId] || characterKnowledge.jan;
  const lower = userMessage.toLowerCase();

  // ১. ইমোশন চেক
  const sadWords = ["মন খারাপ", "sad", "দুঃখ", "কষ্ট", "কাঁদ", "depressed"];
  const happyWords = ["খুশি", "happy", "ভালো লাগছে", "আনন্দ", "গর্ব"];
  const angryWords = ["রাগ", "angry", "বিরক্ত", "ক্ষুব্ধ"];
  const tiredWords = ["ক্লান্ত", "tired", "অবসন্ন", "ঘুমাতে"];

  if (sadWords.some((w) => lower.includes(w))) {
    return pickRandom(kb.emotional.sad);
  }
  if (happyWords.some((w) => lower.includes(w))) {
    return pickRandom(kb.emotional.happy);
  }
  if (angryWords.some((w) => lower.includes(w))) {
    return pickRandom(kb.emotional.angry);
  }
  if (tiredWords.some((w) => lower.includes(w))) {
    return pickRandom(kb.emotional.tired);
  }

  // ২. নলেজ বেস চেক
  for (const entry of kb.knowledge) {
    if (entry.keywords.some((k) => lower.includes(k.toLowerCase()))) {
      return pickRandom(entry.responses);
    }
  }

  // ৩. ফলব্যাক
  return pickRandom(kb.fallbacks);
}

function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}
